export const shells = ["bash", "zsh", "fish", "powershell", "nushell"] as const;
export type Shell = typeof shells[number];
export const completionFilename = (shell: Shell) => ({ bash: "lab.bash", zsh: "_lab", fish: "lab.fish", powershell: "lab.ps1", nushell: "lab.nu" })[shell];

export function completionScript(shell: Shell): string {
  const header = "# Generated by FloatLab. Run pnpm commands:generate to update.\n";
  const scripts: Record<Shell, string> = {
    bash: String.raw`_lab_complete() {
  local candidate suffix part previous i trim="" index=$((COMP_CWORD - 1))
  local -a words=() normalized=()
  words=("\${COMP_WORDS[@]:1}")
  if [[ -n "\${COMP_LINE-}" ]]; then
    local remainder="\${COMP_LINE:COMP_POINT}" current="\${words[index]-}"
    for ((i=\${#current}; i>0; i--)); do
      part="\${current: -i}"
      if [[ "$remainder" == "$part"* ]]; then words[index]="\${current:0:\${#current}-i}"; break; fi
    done
  fi
  # Readline splits inline values at '=' and ':'; restore the original argument.
  for ((i=0; i<\${#words[@]}; i++)); do
    part=\${words[i]}
    if [[ "$part" == '=' || "$part" == ':' ]]; then
      previous=$((\${#normalized[@]} - 1))
      if ((previous >= 0)); then
        normalized[previous]+="$part\${words[i+1]-}"
        if ((i <= COMP_CWORD - 1)); then ((index--)); fi
        if ((i+1 < \${#words[@]})); then
          if ((i+1 <= COMP_CWORD - 1)); then ((index--)); fi
          ((i++))
        fi
        continue
      fi
    fi
    normalized+=("$part")
  done
  ((index < 0)) && index=0
  if [[ "\${normalized[index]-}" == --*=* && "\${words[COMP_CWORD-1]-}" != --* ]]; then
    trim="\${normalized[index]%%=*}="
  fi
  COMPREPLY=()
  while IFS=$'\t' read -r candidate suffix; do
    candidate=\${candidate#"$trim"}
    printf -v candidate '%q' "$candidate"
    [[ "$suffix" == space ]] && candidate+=' '
    COMPREPLY+=("$candidate")
  done < <(command lab completion resolve --shell bash --raw-words --index "$index" -- "\${normalized[@]}" 2>/dev/null)
}
complete -o nospace -F _lab_complete lab
`,
    zsh: String.raw`#compdef lab
_lab() {
  local candidate suffix
  local -a arguments=("\${(@Q)words[2,-1]}")
  if (( \${+PREFIX} )); then arguments[CURRENT-1]="\${(Q)PREFIX}"; fi
  while IFS=$'\t' read -r candidate suffix; do
    [[ "$suffix" == space ]] && compadd -S ' ' -- "$candidate" || compadd -S '' -- "$candidate"
  done < <(command lab completion resolve --shell zsh --index "$((CURRENT - 2))" -- "\${arguments[@]}" 2>/dev/null)
}
compdef _lab lab
`,
    fish: String.raw`function __lab_complete
  set -l words (commandline -opc)
  set -e words[1]
  set -l current (commandline -ct)
  command lab completion resolve --shell fish --index (count $words) -- $words "$current" 2>/dev/null
end
complete -c lab -f -a '(__lab_complete)'
`,
    powershell: String.raw`Register-ArgumentCompleter -Native -CommandName lab -ScriptBlock {
  param($wordToComplete, $commandAst, $cursorPosition)
  $words = @()
  foreach ($element in $commandAst.CommandElements | Select-Object -Skip 1) {
    if ($element.Extent.StartOffset -ge $cursorPosition) { break }
    if ($element -is [System.Management.Automation.Language.StringConstantExpressionAst]) {
      $words += $element.Value
    } else {
      $words += $element.Extent.Text
    }
  }
  $last = $commandAst.CommandElements | Select-Object -Last 1
  if (!$wordToComplete -and ($words.Count -eq 0 -or $cursorPosition -gt $last.Extent.EndOffset)) { $words += '' }
  if ($words.Count -gt 0) { $words[-1] = $wordToComplete }
  $index = [Math]::Max(0, $words.Count - 1)
  $results = & lab completion resolve --shell powershell --index $index -- @words 2>$null | ConvertFrom-Json
  foreach ($item in $results) {
    [System.Management.Automation.CompletionResult]::new($item.completionText, $item.value, 'ParameterValue', $(if ($item.description) { $item.description } else { $item.value }))
  }
}
`,
    nushell: String.raw`# Load with: source /path/to/lab.nu
let lab_previous_completer = $env.config.completions.external.completer
$env.config.completions.external.completer = {|spans|
  if ($spans.0 | path basename) == 'lab' {
    let words = ($spans | skip 1)
    let index = ([0 (($words | length) - 1)] | math max)
    try { ^lab completion resolve --shell nushell --index $index -- ...$words | from json } catch { [] }
  } else if $lab_previous_completer != null {
    do $lab_previous_completer $spans
  } else { null }
}
`,
  };
  const script = scripts[shell].replaceAll("\\$", "$");
  return shell === "zsh" ? script.replace("#compdef lab\n", "#compdef lab\n" + header) : header + script;
}
