import { enableAutoUnmount, mount } from '@vue/test-utils'
import { afterEach, describe, expect, it, vi } from 'vitest'
import UiPlateCard from './UiPlateCard.vue'
enableAutoUnmount(afterEach)
afterEach(() => vi.useRealTimers())
describe('Plate card', () => {
  it('shows inset host identity and preserves native attributes and clicks', async () => {
    const click = vi.fn()
    const wrapper = mount(UiPlateCard, { props: { label: 'Running', active: true, host: 'node-01', hostHealth: 'online', count: 2 }, attrs: { onClick: click, 'aria-label': 'App runtime' } })
    expect(wrapper.get('.plate-host').text()).toContain('ND1')
    expect(wrapper.find('.plate-host i').exists()).toBe(false)
    expect(wrapper.get('.plate-host').text()).toContain('+1')
    expect(wrapper.attributes('aria-label')).toBe('App runtime')
    expect(wrapper.classes()).toContain('is-active')
    expect(wrapper.find('.plate-edit-icon').exists()).toBe(true)
    await wrapper.trigger('click')
    expect(click).toHaveBeenCalledOnce()
  })
  it('fills and drains only on actual state changes and supports restart motion', async () => {
    const wrapper = mount(UiPlateCard, { props: { label: 'Stopped' } })
    expect(wrapper.classes().some(name => name.startsWith('water-'))).toBe(false)
    await wrapper.setProps({ label: 'Starting', busy: true })
    expect(wrapper.classes()).toContain('water-start')
    await wrapper.setProps({ label: 'Running', active: true, busy: false })
    expect(wrapper.classes()).not.toContain('water-start')
    await wrapper.setProps({ label: 'Stopping', active: false, busy: true })
    expect(wrapper.classes()).toContain('water-stop')
    await wrapper.setProps({ label: 'Stopped', busy: false, motion: 'restart' })
    expect(wrapper.classes()).toContain('water-restart')
    await wrapper.setProps({ label: 'Running', active: true, motion: undefined })
    expect(wrapper.classes()).toContain('water-start')
    await wrapper.get('.runtime-liquid').trigger('animationend')
    expect(wrapper.classes()).not.toContain('water-start')
  })
  it('shows real determinate progress and clamps invalid bounds', async () => {
    const wrapper = mount(UiPlateCard, { props: { label: 'Syncing', kind: 'replication', busy: true, progress: 42 } })
    expect(wrapper.get('[role="progressbar"]').attributes('aria-valuenow')).toBe('42')
    expect(wrapper.get('.plate-percent').text()).toBe('42%')
    await wrapper.setProps({ progress: 200 })
    expect(wrapper.get('[role="progressbar"]').attributes('aria-valuenow')).toBe('100')
    await wrapper.setProps({ progress: -2 })
    expect(wrapper.get('[role="progressbar"]').attributes('aria-valuenow')).toBe('0')
  })
  it('does not invent a percentage for jobs without a total', () => {
    const wrapper = mount(UiPlateCard, { props: { label: 'Syncing', kind: 'backup', busy: true, detail: 'Running · total unavailable' } })
    expect(wrapper.get('[role="progressbar"]').attributes('aria-valuenow')).toBeUndefined()
    expect(wrapper.get('[role="progressbar"]').attributes('aria-valuetext')).toContain('Running')
    expect(wrapper.find('.plate-percent').exists()).toBe(false)
    expect(wrapper.get('.plate-progress').classes()).toContain('indeterminate')
  })
  it('disables actions without hiding failed transfer state', async () => {
    const click = vi.fn()
    const wrapper = mount(UiPlateCard, { props: { label: 'Failed', kind: 'backup', tone: 'error', disabled: true }, attrs: { onClick: click } })
    expect(wrapper.classes()).toContain('error')
    await wrapper.trigger('click')
    expect(click).not.toHaveBeenCalled()
  })
  it.each([[0, 'just now'], [5, '5m ago'], [120, '2h ago'], [2880, '2d ago'], [-1, 'just now']])('shows completed backup age for %s minutes', (minutes, age) => {
    vi.useFakeTimers(); vi.setSystemTime(new Date('2026-11-04T12:00:00Z'))
    const completedAt = new Date(Date.now() - minutes * 60_000).toISOString()
    const wrapper = mount(UiPlateCard, { props: { kind: 'backup', label: 'Synced', completedAt, host: 'atlas' } })
    expect(wrapper.text()).toContain('Backed up')
    expect(wrapper.get('time').text()).toBe(`· ${age}`)
    expect(wrapper.get('time').attributes('datetime')).toBe(completedAt)
    expect(wrapper.attributes('aria-label')).toContain(age)
  })
  it('updates backup age as time passes and cleans up the clock', async () => {
    vi.useFakeTimers(); vi.setSystemTime(new Date('2026-11-04T12:00:00Z'))
    const wrapper = mount(UiPlateCard, { props: { kind: 'backup', label: 'Synced', completedAt: new Date().toISOString() } })
    await vi.advanceTimersByTimeAsync(60_000)
    expect(wrapper.get('time').text()).toContain('1m ago')
    await wrapper.setProps({ completedAt: 'invalid' })
    expect(wrapper.find('time').exists()).toBe(false)
    expect(vi.getTimerCount()).toBe(0)
    await wrapper.setProps({ completedAt: new Date().toISOString() })
    wrapper.unmount()
    expect(vi.getTimerCount()).toBe(0)
  })
  it('keeps replication synced and never invents backup freshness', () => {
    expect(mount(UiPlateCard, { props: { kind: 'replication', label: 'Synced' } }).text()).toContain('Synced')
    const wrapper = mount(UiPlateCard, { props: { kind: 'backup', label: 'Synced' } })
    expect(wrapper.text()).toContain('Backed up')
    expect(wrapper.find('time').exists()).toBe(false)
  })
})
